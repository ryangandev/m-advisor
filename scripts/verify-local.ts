const exec = promisify(execFile);

/** A 48 kHz stereo 16-bit WAV header for the stitched stream. */
function wavHeader(dataBytes: number): Buffer {
  const header = Buffer.alloc(44);
  header.write("RIFF", 0); header.writeUInt32LE(36 + dataBytes, 4); header.write("WAVE", 8);
  header.write("fmt ", 12); header.writeUInt32LE(16, 16); header.writeUInt16LE(1, 20); header.writeUInt16LE(2, 22);
  header.writeUInt32LE(48_000, 24); header.writeUInt32LE(48_000 * 4, 28); header.writeUInt16LE(4, 32); header.writeUInt16LE(16, 34);
  header.write("data", 36); header.writeUInt32LE(dataBytes, 40);
  return header;
}
async function verify(): Promise<void> {
  const codec = ffmpeg;
  if (!codec) throw new Error("FFmpeg is unavailable.");
  // This verifier deliberately uses isolated mock data and no Discord connection.
  process.env.RIOT_MODE = "mock";
  const directory = await mkdtemp(path.join(os.tmpdir(), "m-advisor-e2e-"));
  process.env.DATABASE_PATH = path.join(directory, "bot.sqlite3");
  const evidenceDirectory = path.resolve("test-results");
  await mkdir(evidenceDirectory, { recursive: true });
  const started = performance.now();
  let opusBytes = 0;
  let speechSeconds = 0;
  let announceStarted = 0;
  let firstAudioSeconds = 0;
  let audioSeconds = 0;
  const chunks: Array<{ text: string; generationSeconds: number }> = [];
  let monitor: GameMonitor | undefined;
  const messages: Array<{ embeds: Array<{ toJSON: () => { title?: string; description?: string; fields?: Array<{ value: string }> } }> }> = [];
  const channel = { id: "local-test-channel", guild: { id: "local-test-guild" }, members: new Map([["local-test-member", {}]]), send: async (message: typeof messages[number]) => { messages.push(message); } } as unknown as VoiceChannel;
  let spokenText = "";
  const voice = new VoiceAnnouncementService({
    // Each sentence chunk is generated by the installed Qwen model while earlier chunks "play".
    generate: async (text, style, signal) => {
      if (chunks.length === 0) console.log("Generating the simulated match announcement with the installed Qwen model, one sentence chunk at a time...");
      spokenText += text;
      const startedSpeech = performance.now();
      const file = await generateTTS(text, style, signal);
      const generationSeconds = (performance.now() - startedSpeech) / 1000;
      speechSeconds += generationSeconds;
      chunks.push({ text, generationSeconds });
      return file;
    },
    // Simulated transport: the real decoder and stitching produce the PCM stream Discord would receive.
    play: async (_channel, audio) => {
      const stream: Buffer[] = [];
      for await (const file of audio) {
        if (stream.length === 0) firstAudioSeconds = (performance.now() - announceStarted) / 1000;
        stream.push(prepareSpeechPcm(await decodeSpeechFile(file), stream.length === 0 ? 0 : SENTENCE_PAUSE_MS));
      }
      const pcm = Buffer.concat(stream);
      audioSeconds = pcm.length / (48_000 * 4);
      await writeFile(path.join(evidenceDirectory, "local-e2e.wav"), Buffer.concat([wavHeader(pcm.length), pcm]));
      const { stdout } = await exec(codec, ["-hide_banner", "-loglevel", "error", "-i", path.join(evidenceDirectory, "local-e2e.wav"), "-c:a", "libopus", "-f", "ogg", "pipe:1"], { encoding: "buffer", maxBuffer: 16 * 1024 * 1024 });
      assert.equal(stdout.subarray(0, 4).toString(), "OggS");
      opusBytes = stdout.length;
      assert.ok(opusBytes > 100);
    },
    cleanup: file => rm(file, { force: true }),
  });
  try {
    const account = await getAccountByRiotId("MockLoss", "NA1");
    setMemberAccounts(channel.guild.id, "local-test-member", [account]);
    monitor = new GameMonitor({ latest: getLatestSRMatchId, detail: getMatchDetail, members: listTrackedMembers, resolveChannel: () => channel,
      announce: (guild, text, style, resolve, allowed, signal) => {
        announceStarted = performance.now();
        return voice.announce(guild, text, style, resolve, allowed, signal);
      },
      events: (matchId, detail) => fetchMatchEvents(matchId, detail), record: recordHorseRecords,
      mock: () => getRiotMode() === "mock", log: error => { throw error; }, info: message => console.log(message) });
    const client = {} as Client;
    monitor.sync(client, channel.guild.id, ["local-test-member"]);
    assert.equal((await monitor.poll(client, channel.guild.id)).announced, 0);
    simulateMockMatch(account.puuid, "loss");
    assert.deepEqual(await monitor.poll(client, channel.guild.id), { announced: 1, errors: 0 });
    assert.deepEqual(await monitor.poll(client, channel.guild.id), { announced: 0, errors: 0 });
    assert.equal(messages.length, 1);
    const embed = messages[0].embeds[0].toJSON();
    assert.match(embed.title ?? "", /模拟战报/);
    assert.match(embed.description ?? "", /这局输了/);
    for (const tier of ["特等马", "上等马", "中等马", "下等马", "没有马"]) assert.ok(spokenText.includes(`${tier}，`), `speech ranks ${tier}`);
    const report = { checkedAt: new Date().toISOString(), data: "mock", speech: "real offline Qwen", spokenText, spokenCharacters: spokenText.length, codec: "real FFmpeg Opus", discordTransport: "simulated, not live", baselineNotSpoken: true, trackedDefeatCorrect: true, duplicateNotSpoken: true, opusBytes, chunks, speechSeconds, firstAudioSeconds, audioSeconds, totalSeconds: (performance.now() - started) / 1000 };
    await writeFile(path.join(evidenceDirectory, "local-e2e.json"), JSON.stringify(report, null, 2) + "\n");
    console.log(JSON.stringify(report, null, 2));
  } finally {
    monitor?.stopAll();
    await shutdownTTS();
    closeDatabase();
    await rm(directory, { recursive: true, force: true });
  }
}
void verify().catch((error: unknown) => { console.error(error instanceof Error ? error.message : "Local verification failed."); process.exitCode = 1; });
